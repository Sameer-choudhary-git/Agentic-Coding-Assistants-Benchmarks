import { json, type Row } from '../db/database.ts';
import type { AssistantRecord, EvaluationRecord, EventRecord, ExperimentRecord, PlannedAttempt, RunRecord, TaskRecord } from '../types.ts';

const n = (v: unknown): number | null => (v === null || v === undefined ? null : Number(v));
const s = (v: unknown): string | null => (v === null || v === undefined ? null : String(v));
const b = (v: unknown): boolean | null => (v === null || v === undefined ? null : Number(v) === 1);

export const toTask = (r: Row): TaskRecord => ({
  id: String(r.id),
  title: String(r.title),
  category: String(r.category),
  difficulty: String(r.difficulty),
  kind: String(r.kind),
  version: String(r.version),
  testVersion: String(r.test_version),
  taskHash: String(r.task_hash),
  promptHash: String(r.prompt_hash),
  testHash: String(r.test_hash),
  starterHash: String(r.starter_hash),
  validationStatus: String(r.validation_status),
  validatedAt: s(r.validated_at),
  expectedAcceptanceTotal: n(r.expected_acceptance_total),
  prompt: String(r.prompt),
  metadata: json(r.metadata_json, {}),
  syncedAt: String(r.synced_at),
});

